export function initLightbox() {
  const lightbox = document.getElementById("custom-lightbox");
  const imgContainer = document.querySelector(".lightbox-image-container img");
  const titleEl = document.querySelector(".lightbox-title");
  const counterEl = document.querySelector(".lightbox-counter");
  const closeBtn = document.querySelector(".lightbox-close");
  const prevBtn = document.querySelector(".lightbox-prev");
  const nextBtn = document.querySelector(".lightbox-next");
  const triggers = document.querySelectorAll(".work-item");
  
  if (!lightbox) return;
  
  let activeGallery = [];
  let activeIndex = 0;
  const decodedCache = new Map();
  
  triggers.forEach((item) => {
    item.addEventListener("click", (e) => {
      e.preventDefault();
      
      const projectId = item.getAttribute("data-project-id");
      const titleText = item.querySelector(".work-title")?.textContent || "Project Photo";
      
      activeGallery = [];
      
      if (projectId && PROJECT_GALLERIES[projectId]) {
        const pData = PROJECT_GALLERIES[projectId];
        pData.images.forEach((imgSrc) => {
          activeGallery.push({
            src: imgSrc,
            projectTitle: pData.title,
            subtitle: pData.subtitle
          });
        });
        activeIndex = 0;
      } else {
        const img = item.querySelector(".work-image-wrap img") || item.querySelector("img");
        if (img) {
          activeGallery.push({
            src: img.getAttribute("src"),
            projectTitle: titleText,
            subtitle: "Project Photo"
          });
        }
        activeIndex = 0;
      }
      
      if (activeGallery.length > 0) {
        renderCurrentPhoto(true);
        openLightbox();
      }
    });
  });
  
  function preloadAndDecode(src) {
    if (!src || decodedCache.has(src)) return;
    
    const img = new Image();
    img.src = src;
    decodedCache.set(src, img);
    
    if ("decode" in img) {
      img.decode().catch(() => {});
    }
  }

  function preloadNeighbors(index) {
    if (!activeGallery.length) return;
    const len = activeGallery.length;
    
    for (let offset = -3; offset <= 3; offset++) {
      if (offset === 0) continue;
      const targetIdx = (index + offset + len) % len;
      preloadAndDecode(activeGallery[targetIdx].src);
    }
  }

  function renderCurrentPhoto(instant = false) {
    if (!activeGallery.length || !imgContainer) return;
    
    const current = activeGallery[activeIndex];
    
    if (titleEl) titleEl.textContent = current.projectTitle;
    if (counterEl) counterEl.textContent = `Photo ${activeIndex + 1} of ${activeGallery.length}`;
    
    preloadNeighbors(activeIndex);
    
    if (instant || decodedCache.has(current.src)) {
      imgContainer.src = current.src;
      imgContainer.style.opacity = "1";
    } else {
      const loaderImg = new Image();
      loaderImg.src = current.src;
      
      const applySrc = () => {
        imgContainer.src = current.src;
        imgContainer.style.opacity = "1";
        decodedCache.set(current.src, loaderImg);
      };

      if ("decode" in loaderImg) {
        loaderImg.decode().then(applySrc).catch(applySrc);
      } else {
        loaderImg.onload = applySrc;
        if (loaderImg.complete) applySrc();
      }
    }
  }
  
  function openLightbox() {
    lightbox.classList.add("active");
    document.body.style.overflow = "hidden";
  }
  
  function closeLightbox() {
    lightbox.classList.remove("active");
    document.body.style.overflow = "";
  }
  
  function showNext() {
    if (!activeGallery.length) return;
    activeIndex = (activeIndex + 1) % activeGallery.length;
    renderCurrentPhoto(false);
  }
  
  function showPrev() {
    if (!activeGallery.length) return;
    activeIndex = (activeIndex - 1 + activeGallery.length) % activeGallery.length;
    renderCurrentPhoto(false);
  }
  
  if (closeBtn) closeBtn.addEventListener("click", (e) => { e.stopPropagation(); closeLightbox(); });
  if (nextBtn) nextBtn.addEventListener("click", (e) => { e.stopPropagation(); showNext(); });
  if (prevBtn) prevBtn.addEventListener("click", (e) => { e.stopPropagation(); showPrev(); });
  
  lightbox.addEventListener("click", (e) => {
    if (e.target === lightbox) {
      closeLightbox();
    }
  });
  
  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("active")) return;
    if (e.key === "Escape") closeLightbox();
    if (e.key === "ArrowRight") showNext();
    if (e.key === "ArrowLeft") showPrev();
  });
}
